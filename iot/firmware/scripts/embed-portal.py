"""Embed local HTML/CSS/module JS into flash. CLI --check verifies the snapshot."""
from pathlib import Path
import sys

def embed(root, check=False):
    portal = root / 'portal'
    page = (portal / 'index.html').read_text(encoding="utf-8")
    css = (portal / 'style.css').read_text(encoding="utf-8")
    script = (portal / 'app.js').read_text(encoding="utf-8")
    if '</script' in script.lower() or '</style' in css.lower():
        raise ValueError('Embedded source contains a closing HTML tag')
    page = page.replace('/*PORTAL_CSS*/', css).replace('/*PORTAL_JS*/', script)
    if ')HTML"' in page:
        raise ValueError('Embedded source collides with the C++ raw delimiter')
    content = '#pragma once\n#include <Arduino.h>\n// Generated by scripts/embed-portal.py; edit portal source files.\nnamespace irrigation {\nstatic const char localPortalPage[] PROGMEM = R"HTML(' + page + ')HTML";\n}\n'
    target = portal / 'LocalPortalPage.h'
    if check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit('Embedded portal is stale: run python iot/firmware/scripts/embed-portal.py')
    elif not target.exists() or target.read_text(encoding="utf-8") != content:
        target.write_text(content,encoding="utf-8",newline="\n")
    return len(page.encode())

if 'Import' in globals():
    Import('env')
    embed(Path(env.subst('$PROJECT_DIR')))
else:
    print(f'Portal: {embed(Path(__file__).resolve().parents[1], "--check" in sys.argv)} bytes embedded')
